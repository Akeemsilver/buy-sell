const assert = require('assert');
const D = require('../js/invdesign.js');
const ids = D.DESIGNS.map((d) => d.id);
assert.strictEqual(new Set(ids).size, ids.length, 'design ids are unique');
assert.deepStrictEqual(ids, ['classic', 'fade', 'deep', 'dusk', 'sunrise', 'glow']);
assert.strictEqual(D.find('wave').id, 'classic', 'a removed or unknown design falls back to classic');
const f = D.colours('deep', '#7a1f33');
assert.strictEqual(f.head, '#7a1f33'); assert.ok(/^#[0-9a-f]{6}$/.test(f.tint) && f.tint !== f.head && /^#[0-9a-f]{6}$/.test(f.band));
assert.strictEqual(D.colours('classic', '#7a1f33').head, '#cea8bd', 'Classic keeps its own colours');
assert.strictEqual(D.mix('#000000', '#ffffff', 0.5), '#808080');
const own = D.colours('dusk', '#7a1f33', { color: '#1d5fb4', light: 10, blend: 70 });
assert.notStrictEqual(own.head, '#1d5fb4', 'lighter changes the colour'); assert.strictEqual(own.blend, 70);
assert.strictEqual(D.colours('dusk', '#7a1f33').blend, 45); assert.strictEqual(D.colours('sunrise', '#7a1f33', { blend: '' }).blend, -40);
assert.strictEqual(D.colours('deep', '#7a1f33', { color: '#1d5fb4', light: 0 }).head, '#1d5fb4', 'own colour replaces the theme colour');
assert.ok(D.colours('deep', '#7a1f33', { light: 15 }).head !== D.colours('deep', '#7a1f33', { light: -15 }).head);
assert.strictEqual(D.hsvHex(0, 1, 1), '#ff0000'); assert.strictEqual(D.hsvHex(120, 1, 1), '#00ff00'); assert.strictEqual(D.hsvHex(0, 0, 1), '#ffffff'); assert.strictEqual(D.hsvHex(240, 1, 0.5), '#000080');
['#7a1f33', '#1d5fb4', '#ffcc00', '#808080'].forEach((c) => { const h = D.hsvOf(c); assert.ok(Math.abs(parseInt(D.hsvHex(h.h, h.s, h.v).slice(1), 16) - parseInt(c.slice(1), 16)) < 0x030303, 'round trip ' + c); });
console.log('invoice design tests passed');
